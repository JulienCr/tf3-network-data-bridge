#!/usr/bin/env python3
"""Mirror the Transport Fever 3 scripting reference as compact Markdown in docs/tf3-api/ (stdlib only).

Source: https://wiki.transportfever3.com/script-doc/ (HTML generated by Teal). Each page becomes one .md file with the
page chrome, links and duplicated summaries removed; INDEX.md lists every page with a size and a one-line summary.
Usage: py tools/update_api_docs.py [--out DIR]
Nothing is deleted unless every page was fetched, so a failed run leaves the previous mirror intact.
"""
import argparse
import datetime
import html
import os
import re
import sys
import time
import urllib.request
from html.parser import HTMLParser

BASE = "https://wiki.transportfever3.com/script-doc/"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_OUT = os.path.join(ROOT, "docs", "tf3-api")
DELAY_SEC = 0.2
SKIP_TAGS = {"style", "script", "button", "nav", "aside", "head", "footer"}
HEADING_PREFIX = {"h1": "#", "h2": "##", "h3": "##", "h4": "###", "h5": "####", "h6": "####"}


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "tf3-api-docs-mirror/1.0"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read().decode("utf-8")


class ToMarkdown(HTMLParser):
    """Walks the page from its first <h1> and writes headings, signatures, paragraphs and lists as plain text."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.out = []
        self.buf = []
        self.started = False
        self.skip = 0
        self.in_pre = False
        self.pre = []
        self.heading = None
        self.list_depth = 0
        self.in_li = False
        self.in_b = False

    def flush(self, prefix=""):
        text = re.sub(r"\s+", " ", "".join(self.buf)).strip()
        self.buf = []
        if text:
            self.out.append(prefix + text)

    def handle_starttag(self, tag, attrs):
        if tag == "h1":
            self.started = True
        if not self.started:
            return
        if tag in SKIP_TAGS:
            self.skip += 1
            return
        if self.skip:
            return
        if tag in HEADING_PREFIX:
            self.flush()
            self.heading = tag
        elif tag == "pre":
            self.flush()
            self.in_pre, self.pre = True, []
        elif tag in ("ul", "ol"):
            self.flush()
            self.list_depth += 1
        elif tag == "li":
            self.flush()
            self.in_li = True
        elif tag == "p":
            self.flush()
        elif tag == "br":
            self.buf.append(" ")
        elif tag == "b":
            self.in_b = True

    def handle_endtag(self, tag):
        if not self.started:
            return
        if tag in SKIP_TAGS:
            self.skip = max(0, self.skip - 1)
            return
        if self.skip:
            return
        if tag in HEADING_PREFIX and self.heading == tag:
            text = re.sub(r"\s+", " ", "".join(self.buf)).replace("\U0001F517", "").strip()
            self.buf = []
            self.out.append("")
            self.out.append(HEADING_PREFIX[tag] + " " + text)
            self.heading = None
        elif tag == "pre":
            code = "".join(self.pre).strip()
            self.in_pre = False
            if code:
                self.out.append("```lua\n" + code + "\n```")
        elif tag in ("ul", "ol"):
            self.list_depth -= 1
        elif tag == "li":
            self.flush("  " * max(0, self.list_depth - 1) + "- ")
            self.in_li = False
        elif tag == "p":
            self.flush()
        elif tag == "b":
            self.in_b = False
            label = re.sub(r"\s+", " ", "".join(self.buf)).strip()
            self.buf = []
            if label:
                self.out.append(label + ":")

    def handle_data(self, data):
        if not self.started or self.skip:
            return
        (self.pre if self.in_pre else self.buf).append(data)


def record_members(block):
    first = re.match(r"\S.*?  (\w+) ?: ", block.splitlines()[0])
    return ([first.group(1)] if first else []) + re.findall(r"^  (\w+) ?: ", block, re.M)


def module_summary(block):
    lines = block.splitlines()
    end = next((i for i, l in enumerate(lines) if l == "end"), len(lines))
    main = record_members("\n".join(lines[:end]))
    names = re.findall(r"^\s*(?:global )?(?:record|enum|interface) (\w+)", "\n".join(lines[end:]), re.M)
    head = re.match(r"(?:global )?record (\w+)", lines[0])
    text = "Declarations (all detailed below). %s: %s" % (head.group(1) if head else "main", ", ".join(main))
    return text + ("\nOther types: " + ", ".join(names) if names else "")


def dedupe_records(md):
    """Replaces the module summary block (it repeats every entry below) and record blocks whose members each have
    their own '## Record.member' entry by plain name lists."""
    first = md.find("\n## ")
    head, md = md[:first], md[first:]
    head = re.sub(r"```lua\n((?:global )?(?:record|enum)\b.{500,}?)\n```", lambda m: module_summary(m.group(1)), head,
                  flags=re.S)
    md = head + md
    headings = set(re.findall(r"^## (\S+)$", md, re.M))
    def shrink(m):
        title, block = m.group(1), m.group(2)
        decl = re.match(r"\s*(?:global )?record (\w+)", block)
        if not decl:
            return m.group(0)
        name = title or decl.group(1)
        members = record_members(block)
        if members and sum(name + "." + x in headings for x in members) * 2 >= len(members):
            return ("## %s\n" % title if title else "") + "%s members (detailed below): %s" % (name, ", ".join(members))
        return m.group(0)
    return re.sub(r"(?:^## (\S+)\n)?```lua\n(.*?)\n```", shrink, md, flags=re.M | re.S)


def to_markdown(page_html):
    p = ToMarkdown()
    p.feed(page_html)
    p.flush()
    text = re.sub(r"(\w) : ", r"\1: ", "\n".join(p.out))
    text = re.sub(r"^(\s*- \w+) :", r"\1: ", text, flags=re.M)
    return re.sub(r"\n{3,}", "\n\n", dedupe_records(text)).strip() + "\n"


def page_links(index_html):
    seen, out = set(), []
    for href in re.findall(r'href="([^"#]+\.html)"', index_html):
        if href.startswith(("/", "http")) or href in seen:
            continue
        seen.add(href)
        out.append(href)
    return sorted(out)


def summary_of(md):
    for line in md.splitlines()[1:]:
        line = line.strip()
        if line and not line.startswith(("#", "```", "-")):
            return html.unescape(line)[:110]
    return ""


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", default=DEFAULT_OUT)
    out_dir = ap.parse_args().out

    pages = page_links(fetch(BASE))
    print("%d pages to fetch" % len(pages))
    results, failed = {}, []
    for i, href in enumerate(pages, 1):
        try:
            results[href[:-5] + ".md"] = to_markdown(fetch(BASE + href))
        except Exception as e:
            failed.append((href, e))
            print("FAILED %s: %s" % (href, e), file=sys.stderr)
        if i % 25 == 0:
            print("  %d/%d" % (i, len(pages)))
        time.sleep(DELAY_SEC)
    if failed:
        print("%d pages failed: nothing written" % len(failed), file=sys.stderr)
        return 1

    for rel, md in results.items():
        path = os.path.join(out_dir, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(md)

    for dirpath, _, files in os.walk(out_dir):
        for name in files:
            rel = os.path.relpath(os.path.join(dirpath, name), out_dir).replace(os.sep, "/")
            if name.endswith(".md") and rel != "INDEX.md" and rel not in results:
                os.unlink(os.path.join(dirpath, name))
                print("removed stale " + rel)

    lines = [
        "# Transport Fever 3 scripting reference (local mirror)",
        "",
        "Source: " + BASE + " (fetched " + datetime.date.today().isoformat() + "). Refresh: `py tools/update_api_docs.py`.",
        "One file per module. Find a function with `grep -rn \"makeVehicleBuyCmd\" docs/tf3-api`, then read only that file.",
        "Columns: file, approx. tokens, summary. `api/` is the engine API; `content/` is the game's own Lua.",
        "",
    ]
    for rel in sorted(results):
        lines.append("%s | ~%dk | %s" % (rel, round(len(results[rel]) / 4000), summary_of(results[rel])))
    with open(os.path.join(out_dir, "INDEX.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    total = sum(len(m) for m in results.values())
    print("wrote %d pages, %.1f MB, ~%dk tokens in total" % (len(results), total / 1e6, total // 4000))
    return 0


if __name__ == "__main__":
    sys.exit(main())
